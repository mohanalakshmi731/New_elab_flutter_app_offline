"""Generates the eLabs and MathZoro app icons for Android, Windows, iOS and macOS.

Sources (same images the web app uses):
  branding/elabs_logo.png     <- web src/assets/elabsLogo.png (the web favicon)
  branding/mathzoro_logo.png  <- web src/assets/mathzorologo.png

To change an icon, replace the source image and run from the project root:
  python tool/make_icons.py          (needs Pillow: pip install pillow)

Outputs:
  Android  android/app/src/{elabs,mathzoro}/res/   (picked by IS_MATHZORO in build.gradle.kts)
  Windows  windows/runner/resources/app_icon.ico, app_icon_mathzoro.ico
           (picked by IS_MATHZORO in windows/runner/CMakeLists.txt + Runner.rc)
  iOS      ios/Runner/Assets.xcassets/AppIcon.appiconset (eLabs),
           AppIcon-MathZoro.appiconset
  macOS    macos/Runner/Assets.xcassets/AppIcon.appiconset (eLabs),
           AppIcon-MathZoro.appiconset
"""

import json
import shutil
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
BRANDING = ROOT / "branding"
WHITE = (255, 255, 255, 255)


# ── Sources ──────────────────────────────────────────────────────────────────

def load_elabs() -> Image.Image:
    """The eLabs logo already has a transparent background; trim it."""
    im = Image.open(BRANDING / "elabs_logo.png").convert("RGBA")
    return im.crop(im.getchannel("A").getbbox())


def load_mathzoro() -> Image.Image:
    """The MathZoro logo is a framed rounded square on a white background.

    Make the white around the frame transparent: near-white, low-saturation
    pixels that are connected to the image border.
    """
    rgb = Image.open(BRANDING / "mathzoro_logo.png").convert("RGB")
    r, g, b = rgb.split()
    lo = ImageChops.darker(ImageChops.darker(r, g), b)
    hi = ImageChops.lighter(ImageChops.lighter(r, g), b)
    sat = ImageChops.difference(hi, lo)
    whiteish = ImageChops.multiply(
        lo.point(lambda v: 255 if v >= 225 else 0),
        sat.point(lambda v: 255 if v <= 24 else 0),
    )
    # Flood the background from every white border pixel (marks it 128).
    w, h = whiteish.size
    border = [(x, 0) for x in range(w)] + [(x, h - 1) for x in range(w)]
    border += [(0, y) for y in range(h)] + [(w - 1, y) for y in range(h)]
    for seed in border:
        if whiteish.getpixel(seed) == 255:
            ImageDraw.floodfill(whiteish, seed, 128, thresh=0)
    alpha = whiteish.point(lambda v: 0 if v == 128 else 255)
    # Pull the edge in by a pixel (drops the light anti-aliased fringe), then soften it.
    alpha = alpha.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(1))
    im = rgb.convert("RGBA")
    im.putalpha(alpha)
    return im.crop(alpha.getbbox())


# ── Drawing helpers ──────────────────────────────────────────────────────────

def fit(logo: Image.Image, size: int, box: float, bg=None, plate=None) -> Image.Image:
    """Square `size` canvas with `logo` scaled to fit `box` (fraction of size), centered.

    bg:    fill the whole canvas (opaque icons, e.g. iOS).
    plate: (fraction, corner_radius_fraction) — a white rounded plate under the logo.
    """
    canvas = Image.new("RGBA", (size, size), bg or (0, 0, 0, 0))
    if plate:
        frac, radius = plate
        inset = round(size * (1 - frac) / 2)
        ImageDraw.Draw(canvas).rounded_rectangle(
            (inset, inset, size - 1 - inset, size - 1 - inset),
            radius=round(size * radius),
            fill=WHITE,
        )
    limit = size * box
    scale = min(limit / logo.width, limit / logo.height)
    w, h = max(1, round(logo.width * scale)), max(1, round(logo.height * scale))
    scaled = logo.resize((w, h), Image.Resampling.LANCZOS)
    canvas.alpha_composite(scaled, ((size - w) // 2, (size - h) // 2))
    return canvas


def save_png(im: Image.Image, path: Path, opaque=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    (im.convert("RGB") if opaque else im).save(path, optimize=True)


# ── Platforms ────────────────────────────────────────────────────────────────

ANDROID_DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""

BACKGROUND_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_icons.py -->
<resources>
    <color name="ic_launcher_background">#FFFFFF</color>
</resources>
"""


def android(app: str, logo: Image.Image, legacy, foreground_box: float):
    res = ROOT / "android" / "app" / "src" / app / "res"
    if res.exists():
        shutil.rmtree(res)
    for density, k in ANDROID_DENSITIES.items():
        # Legacy icon (Android 7): 48dp.
        save_png(legacy(round(48 * k)), res / f"mipmap-{density}" / "ic_launcher.png")
        # Adaptive foreground (Android 8+): 108dp layer, launchers show the middle
        # 72dp through a circle/squircle mask, so the logo stays inside the middle.
        save_png(
            fit(logo, round(108 * k), foreground_box),
            res / f"mipmap-{density}" / "ic_launcher_foreground.png",
        )
    xml = res / "mipmap-anydpi-v26" / "ic_launcher.xml"
    xml.parent.mkdir(parents=True, exist_ok=True)
    xml.write_text(ADAPTIVE_XML, encoding="utf-8")
    color = res / "values" / "ic_launcher_colors.xml"
    color.parent.mkdir(parents=True, exist_ok=True)
    color.write_text(BACKGROUND_XML, encoding="utf-8")


def windows(name: str, logo: Image.Image, box: float):
    path = ROOT / "windows" / "runner" / "resources" / name
    fit(logo, 256, box).save(
        path,
        sizes=[(s, s) for s in (16, 20, 24, 32, 40, 48, 64, 128, 256)],
        bitmap_format="bmp",  # classic DIB entries: safest for every Windows icon API
    )


def apple(platform: str, set_name: str, render, opaque: bool):
    """Writes every image listed in the template's AppIcon.appiconset/Contents.json."""
    assets = ROOT / platform / "Runner" / "Assets.xcassets"
    contents = json.loads((assets / "AppIcon.appiconset" / "Contents.json").read_text())
    out = assets / f"{set_name}.appiconset"
    out.mkdir(parents=True, exist_ok=True)
    if set_name != "AppIcon":
        (out / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n")
    done = set()
    for image in contents["images"]:
        file = image["filename"]
        if file in done:
            continue
        done.add(file)
        points = float(image["size"].split("x")[0])
        px = round(points * int(image["scale"].rstrip("x")))
        save_png(render(px), out / file, opaque=opaque)


def main():
    elabs = load_elabs()
    mathzoro = load_mathzoro()

    # Android ────────────────────────────────────────────────────────────────
    android(
        "elabs",
        elabs,
        legacy=lambda s: fit(elabs, s, 0.84, plate=(0.92, 0.18)),
        foreground_box=58 / 108,
    )
    android(
        "mathzoro",
        mathzoro,
        legacy=lambda s: fit(mathzoro, s, 0.92),
        # 54dp keeps the frame's rounded corners inside a circular mask (radius 36dp).
        foreground_box=54 / 108,
    )

    # Windows (exe, window and taskbar icon) ───────────────────────────────────
    windows("app_icon.ico", elabs, 1.0)
    windows("app_icon_mathzoro.ico", mathzoro, 1.0)

    # iOS: opaque squares, iOS rounds the corners itself ────────────────────────
    apple("ios", "AppIcon", lambda s: fit(elabs, s, 0.80, bg=WHITE), opaque=True)
    apple("ios", "AppIcon-MathZoro", lambda s: fit(mathzoro, s, 0.86, bg=WHITE), opaque=True)

    # macOS: the icon body is ~80% of the canvas, transparent around it ─────────
    apple(
        "macos",
        "AppIcon",
        lambda s: fit(elabs, s, 0.70, plate=(0.805, 0.18)),
        opaque=False,
    )
    apple("macos", "AppIcon-MathZoro", lambda s: fit(mathzoro, s, 0.805), opaque=False)

    print("Icons written.")


if __name__ == "__main__":
    main()
