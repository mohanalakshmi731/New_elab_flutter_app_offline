import java.util.Base64
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("com.android.application")
    id("kotlin-android")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

// ── Flavor from the dart-defines ─────────────────────────────────────────
// `flutter run --dart-define-from-file=.env --dart-define=IS_MATHZORO=true` passes IS_MATHZORO=true
// to Gradle (base64 encoded in the "dart-defines" property). Use it to give the
// MathZoro build its own application id, launcher name and icon, so both apps can be
// installed side by side — no --flavor flag needed.
val dartDefines: Map<String, String> =
    (project.findProperty("dart-defines") as String?)
        ?.split(",")
        ?.mapNotNull {
            // Imported Base64: inside a build script `java.` resolves to the `java` extension.
            val decoded = String(Base64.getDecoder().decode(it), Charsets.UTF_8)
            val i = decoded.indexOf('=')
            if (i > 0) decoded.substring(0, i) to decoded.substring(i + 1) else null
        }
        ?.toMap()
        ?: emptyMap()
val isMathzoro = dartDefines["IS_MATHZORO"] == "true"

android {
    namespace = "com.tedlance.elab_app"
    compileSdk = flutter.compileSdkVersion
    ndkVersion = flutter.ndkVersion

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    defaultConfig {
        applicationId = if (isMathzoro) "com.tedlance.mathzoro" else "com.tedlance.elabs"
        resValue("string", "app_name", if (isMathzoro) "MathZoro" else "eLabs")
        // You can update the following values to match your application needs.
        // For more information, see: https://flutter.dev/to/review-gradle-config.
        minSdk = flutter.minSdkVersion
        targetSdk = flutter.targetSdkVersion
        versionCode = flutter.versionCode
        versionName = flutter.versionName
    }

    // Launcher icon per app (generated by tool/make_icons.py). These folders are not
    // flavor source sets, just an extra res folder chosen by the same IS_MATHZORO switch.
    sourceSets["main"].res.srcDir(if (isMathzoro) "src/mathzoro/res" else "src/elabs/res")

    buildTypes {
        release {
            // TODO: Add your own signing config for the release build.
            // Signing with the debug keys for now, so `flutter run --release` works.
            signingConfig = signingConfigs.getByName("debug")
        }
    }
}

kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
    }
}

flutter {
    source = "../.."
}
